#!/usr/bin/env python3
"""Offline, read-only source lockfile and container-base metadata inventory.

No dependency installs, lifecycle scripts, external requests, application
execution, vulnerability database or media access. Enforce mode reports known
digest/pin gaps by returning exit code 2.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[2]
H40 = re.compile(r"[0-9a-fA-F]{40}\Z")
H64 = re.compile(r"[0-9a-fA-F]{64}\Z")


def scan(root: Path = ROOT) -> dict:
    problems = []
    totals = {}

    def report(level: str, code: str, name: str, detail: str) -> None:
        problems.append(dict(level=level, code=code, location=name, detail=detail))

    with (root / "machine-learning/uv.lock").open("rb") as file:
        uv = tomllib.load(file)
    uv_packages = uv.get("package", [])
    if not uv_packages:
        raise ValueError("uv package list missing")
    uv_git, uv_files, registry_hosts = 0, 0, set()
    for pkg in uv_packages:
        name = str(pkg.get("name", "unknown"))
        place = "machine-learning/uv.lock:" + name
        source = pkg.get("source", {})
        if not isinstance(source, dict):
            report("blocker", "uv-invalid-source", place, "Source not a dictionary")
            continue
        if "git" in source:
            uv_git += 1
            if not H40.fullmatch(str(source["git"]).partition("#")[2]):
                report("blocker", "uv-unpinned-git", place, "Missing full commit SHA")
            else:
                report("review", "uv-git-source-review", place, "Commit pinned; content not independently audited")
        if "registry" in source:
            registry_hosts.add(urlsplit(str(source["registry"])).netloc)
        artifacts = list(pkg.get("wheels", []))
        if pkg.get("sdist"):
            artifacts.append(pkg["sdist"])
        for artifact in artifacts:
            uv_files += 1
            digest = str(artifact.get("hash", ""))
            if not digest.startswith("sha256:") or not H64.fullmatch(digest[7:]):
                report("blocker", "uv-missing-artifact-hash", place, "Wheel or sdist missing recorded SHA-256")
    totals["uv"] = dict(packages=len(uv_packages), artifact_files=uv_files,
                        git_sources=uv_git, registry_hosts=sorted(registry_hosts))

    with (root / "native/Cargo.lock").open("rb") as file:
        cargo = tomllib.load(file)
    cargo_packages = cargo.get("package", [])
    if not cargo_packages:
        raise ValueError("Cargo package list missing")
    cargo_git = cargo_registry = 0
    for pkg in cargo_packages:
        name = str(pkg.get("name", "unknown"))
        place = "native/Cargo.lock:" + name
        source = str(pkg.get("source", ""))
        if source.startswith("registry+"):
            cargo_registry += 1
            if not H64.fullmatch(str(pkg.get("checksum", ""))):
                report("blocker", "cargo-missing-checksum", place, "Registry artifact lacks SHA-256 checksum")
        elif source.startswith("git+"):
            cargo_git += 1
            if not H40.fullmatch(source.partition("#")[2]):
                report("blocker", "cargo-unpinned-git", place, "Git source lacks full commit SHA")
            else:
                report("review", "cargo-git-source-review", place, "Git commit pinned; code and license not independently audited")
        elif source:
            report("blocker", "cargo-unknown-source", place, "Unsupported dependency source")
    totals["cargo"] = dict(packages=len(cargo_packages),
                           registry_sources=cargo_registry, git_sources=cargo_git)

    dart_totals = {}
    for name in ("mobile/pubspec.lock", "mobile/packages/ui/pubspec.lock"):
        text = (root / name).read_text(encoding="utf-8")
        if not text.startswith("# Generated by pub"):
            report("blocker", "pub-unknown-header", name, "Unrecognized lockfile header")
        section = text.partition("\npackages:\n")[2].split("\nsdks:", 1)[0]
        starts = list(re.finditer(r"(?m)^  ([a-zA-Z0-9_]+):[ \t]*$", section))
        if not starts:
            raise ValueError(name + " has no packages section")
        by_source = {}
        for i, item in enumerate(starts):
            end = starts[i+1].start() if i+1 < len(starts) else len(section)
            body = section[item.end():end]
            package = item.group(1)
            place = name + ":" + package
            found = re.search(r"(?m)^    source: ([a-z]+)[ \t]*$", body)
            if not found:
                report("blocker", "pub-unrecognized-source", place, "Source field missing")
                continue
            source = found.group(1)
            by_source[source] = by_source.get(source, 0) + 1
            if source == "hosted":
                sha = re.search(r'(?m)^      sha256: "?([0-9a-fA-F]+)"?[ \t]*$', body)
                if not sha or not H64.fullmatch(sha.group(1)):
                    report("blocker", "pub-missing-hosted-hash", place, "Hosted package lacks SHA-256 hash")
            elif source == "git":
                ref = re.search(r'(?m)^      ref: "?([0-9a-fA-F]+)"?[ \t]*$', body)
                resolved = re.search(r'(?m)^      resolved-ref: "?([0-9a-fA-F]+)"?[ \t]*$', body)
                if not resolved or not H40.fullmatch(resolved.group(1)):
                    report("blocker", "pub-unpinned-git", place, "Git package lacks resolved 40-digit commit")
                else:
                    if ref and H40.fullmatch(ref.group(1)) and ref.group(1) != resolved.group(1):
                        report("blocker", "pub-conflicting-git-refs", place, "Requested and resolved Git commits disagree")
                    report("review", "pub-git-source-review", place, "Git commit pinned; source review pending")
            elif source not in ("sdk", "path"):
                report("blocker", "pub-unsupported-source", place, "Package source type not supported")
        dart_totals[name] = dict(packages=len(starts), source_types=dict(sorted(by_source.items())))
    totals["dart"] = dart_totals

    dockerfiles = external = 0
    for file in sorted(root.rglob("Dockerfile*")):
        if not file.is_file() or any(x in (".git", "node_modules", "upstream-github-workflows") for x in file.parts):
            continue
        dockerfiles += 1
        stages = set()
        for index, line in enumerate(file.read_text(encoding="utf-8").splitlines(), 1):
            if not re.match(r"^\s*FROM\s+", line, re.I):
                continue
            parts = [x for x in line.strip().split()[1:] if not x.startswith("--platform=")]
            if not parts:
                report("blocker", "docker-missing-base", str(file.relative_to(root)), "FROM has no base")
                continue
            base = parts[0]
            internal = base in stages or ("$" in base and base.startswith(("builder-", "prod-")))
            if not internal:
                external += 1
                digest = base.rsplit("@sha256:", 1)[-1] if "@sha256:" in base else ""
                if not H64.fullmatch(digest):
                    report("blocker", "docker-unpinned-base", str(file.relative_to(root)) + ":" + str(index), "External FROM lacks digest")
            for n, token in enumerate(parts[:-1]):
                if token.upper() == "AS":
                    stages.add(parts[n+1])
    totals["containers"] = dict(dockerfiles=dockerfiles, external_base_references=external)

    problems.sort(key=lambda p: (p["level"], p["code"], p["location"]))
    blockers = sum(p["level"] == "blocker" for p in problems)
    return dict(
        scope="Static lockfiles and Dockerfile FROM only; NOT a vulnerability, container, code, or media scan",
        status="blocked" if blockers else "metadata-only",
        blockers=blockers,
        reviews=sum(p["level"] == "review" for p in problems),
        totals=totals,
        findings=problems,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--enforce", action="store_true")
    args = parser.parse_args()
    try:
        result = scan()
    except (OSError, ValueError, tomllib.TOMLDecodeError) as error:
        print(json.dumps(dict(status="error", detail=str(error))))
        return 3
    print(json.dumps(result, indent=2, sort_keys=True))
    return 2 if args.enforce and result["blockers"] else 0


if __name__ == "__main__":
    sys.exit(main())
